#!/usr/bin/env python3
"""Build hooks/sprites.ts, the mascot animations Backstage draws for subagents.

    python3 scripts/sprites.py default            # the bundled pixel robot (MIT, the repository default)
    python3 scripts/sprites.py clawd [APP_ASAR]   # Clawd, read from the Claude desktop app on your own machine

Clawd and his sprites belong to Anthropic, so this repository ships none of them. The `clawd` command reads them from
the Claude app installed on your machine (macOS: /Applications/Claude.app) and writes them into your local copy only.
Keep that copy to yourself: do not commit or publish the generated file. The app's internal layout can change with any
release; when it does, the command stops with a message and the robot stays in place.

Each animation becomes a strip of 44 x 30 frames laid side by side, the 24 x 16 body centred at (10, 7), so the mascot
sits in the middle of its box whatever it does (a laptop to the right, a raised arm above).
"""
import json
import re
import sys
from pathlib import Path

FRAME_W, FRAME_H = 44, 30
BODY_X, BODY_Y = 10, 7
FPS = 12
# Backstage's states, in the names art.ts uses: running, waiting, done, failed, stopped.
ANIMS = ['laptop', 'look', 'wave', 'dizzy', 'sad']
OUT = Path(__file__).resolve().parent.parent / 'hooks' / 'sprites.ts'


def write(strips, source):
    """strips: anim -> (palette, frames); a frame is a dict {(x, y): palette index} in frame coordinates."""
    lines = [
        f'// {source}',
        '// Generated by scripts/sprites.py: each animation is a strip of 44 x 30 frames side by side, the 24 x 16 body',
        '// centred at (10, 7). Do not edit by hand.',
        '',
        "export type SpriteAnim = 'laptop' | 'look' | 'wave' | 'dizzy' | 'sad'",
        '',
        'export type SpriteStrip = { frames: number; layers: [fill: string, d: string][] }',
        '',
        f'export const FRAME_W = {FRAME_W}',
        f'export const FRAME_H = {FRAME_H}',
        f'export const FPS = {FPS}',
        '',
        'export const SPRITES: Record<SpriteAnim, SpriteStrip> = {',
    ]
    for anim in ANIMS:
        palette, frames = strips[anim]
        paths = {}
        for fi, frame in enumerate(frames):
            for y in range(FRAME_H):
                x = 0
                while x < FRAME_W:
                    c = frame.get((x, y))
                    if c is None:
                        x += 1
                        continue
                    end = x
                    while end < FRAME_W and frame.get((end, y)) == c:
                        end += 1
                    paths.setdefault(c, []).append(f'M{fi * FRAME_W + x} {y}h{end - x}v1h-{end - x}z')
                    x = end
        layers = ', '.join(f"['{palette[c]}', '{''.join(p)}']" for c, p in sorted(paths.items()))
        lines.append(f'  {anim}: {{ frames: {len(frames)}, layers: [{layers}] }},')
    lines.append('}')
    OUT.write_text('\n'.join(lines) + '\n')
    print(f'wrote {OUT}')


# ---------- the default mascot: a small pixel robot, drawn for this project (MIT) ----------

INK, BODY, SHADE, GLOW, SPARK, ZZ = range(6)
ROBOT_PALETTE = ['#141413', '#d97757', '#be684d', '#f4db99', '#e8b34a', '#8f8b84']


class Pixels:
    def __init__(self, dx=0, dy=0):
        self.px, self.dx, self.dy = {}, dx, dy

    def rect(self, x, y, w, h, c):
        """Body-relative rectangle: (0, 0) is the 24 x 16 body box's top left."""
        for yy in range(y, y + h):
            for xx in range(x, x + w):
                fx, fy = BODY_X + xx + self.dx, BODY_Y + yy + self.dy
                if 0 <= fx < FRAME_W and 0 <= fy < FRAME_H:
                    self.px[(fx, fy)] = c


def robot(eyes='open', arm='down', lift=None, bob=0, tip=True, shift=0, extra=None):
    """A boxy robot: square head with an antenna, a neck, a small body with a chest light, thin arms, two legs."""
    p = Pixels(dx=shift, dy=bob)
    p.rect(11, 0, 2, 1, GLOW if tip else SHADE)  # antenna tip
    p.rect(11, 1, 2, 1, SHADE)  # stem
    p.rect(5, 2, 14, 7, BODY)  # head
    p.rect(10, 9, 4, 1, SHADE)  # neck
    p.rect(6, 10, 12, 3, BODY)  # body
    p.rect(11, 11, 2, 1, GLOW if tip else SHADE)  # chest light
    p.rect(3, 10, 3, 1, BODY)  # left arm
    p.rect(3, 11, 1, 1, BODY)
    if arm == 'up':
        p.rect(18, 7, 1, 4, BODY)
        p.rect(18, 6, 3, 1, BODY)
    else:
        p.rect(18, 10, 3, 1, BODY)
        p.rect(20, 11, 1, 1, BODY)
    legs = {'left': (8, 13, 2, 2), 'right': (14, 13, 2, 2)}
    for side, (x, y, w, h) in legs.items():
        # a lifted leg is one pixel shorter; the body bob keeps the feet on the ground
        p.rect(x, y, w, h + (0 if lift == side else 1) - bob, BODY)
    ex = {'open': 0, 'left': -1, 'right': 1}.get(eyes)
    if ex is not None:
        p.rect(8 + ex, 4, 2, 2, INK)
        p.rect(14 + ex, 4, 2, 2, INK)
    elif eyes == 'blink':
        p.rect(8, 5, 2, 1, INK)
        p.rect(14, 5, 2, 1, INK)
    elif eyes == 'x':
        for x0 in (7, 13):
            for dx, dy in ((0, 0), (2, 0), (1, 1), (0, 2), (2, 2)):
                p.rect(x0 + dx, 3 + dy, 1, 1, INK)
    elif eyes == 'dash':
        p.rect(7, 5, 3, 1, INK)
        p.rect(14, 5, 3, 1, INK)
    if extra:
        extra(p)
    return p.px


def zz(step):
    def draw(p):
        y = -3 - step
        p.rect(21, y, 3, 1, ZZ)
        p.rect(22, y + 1, 1, 1, ZZ)
        p.rect(21, y + 2, 3, 1, ZZ)
    return draw


def sparkle(on):
    def draw(p):
        if on:
            p.rect(25, -4, 1, 1, SPARK)
            p.rect(24, -3, 1, 1, SPARK)
            p.rect(26, -3, 1, 1, SPARK)
            p.rect(25, -2, 1, 1, SPARK)
    return draw


def stars(i):
    spots = [(4, -3), (11, -5), (18, -3)]
    def draw(p):
        for k, (x, y) in enumerate(spots):
            if (i + k) % 3 != 0:
                p.rect(x, y, 1, 1, SPARK)
    return draw


def default_strips():
    running = [robot(lift='left' if f < 4 else 'right', bob=1 if f % 4 in (1, 2) else 0, tip=f < 4) for f in range(8)]
    look_eyes = ['open'] * 6 + ['left'] * 6 + ['open'] * 3 + ['blink'] * 2 + ['right'] * 6 + ['blink']
    waiting = [robot(eyes=e, extra=zz((f // 8) % 3)) for f, e in enumerate(look_eyes)]
    done = [robot(arm='up' if (f // 3) % 2 == 0 else 'down', extra=sparkle(f % 4 < 2)) for f in range(12)]
    failed = [robot(eyes='x', shift=-1 if f < 6 else 1, tip=False, extra=stars(f // 4)) for f in range(12)]
    stopped = [robot(eyes='dash', tip=False)]
    strips = dict(zip(ANIMS, [running, waiting, done, failed, stopped]))
    return {k: (ROBOT_PALETTE, v) for k, v in strips.items()}


# ---------- Clawd, read from the Claude desktop app on this machine ----------

CLAWD_ANIMS = {'laptop': 'Laptop', 'look': 'LookingAround', 'wave': 'Waving', 'dizzy': 'Dizzy', 'sad': 'Disappointed'}
DEFAULT_ASAR = '/Applications/Claude.app/Contents/Resources/app.asar'


def asar_file(asar, needle):
    data = Path(asar).read_bytes()
    size = int.from_bytes(data[12:16], 'little')
    header = json.loads(data[16:16 + size].rstrip(b'\0'))
    base = 16 + ((size + 3) // 4) * 4

    def walk(node, path=''):
        for name, entry in node.get('files', {}).items():
            if 'files' in entry:
                yield from walk(entry, f'{path}/{name}')
            else:
                yield f'{path}/{name}', entry

    for path, entry in walk(header):
        if needle in path and path.endswith('.js') and 'offset' in entry:
            start = base + int(entry['offset'])
            return data[start:start + entry['size']].decode('utf-8')
    raise SystemExit(f'no file matching {needle!r} in {asar}; the app has changed, keeping the current sprites')


def sprite_table(src):
    """The minified object literal whose entries look like Laptop:{cat:...,w:..,h:..,base:...,deltas:...}."""
    at = src.find('Laptop:{cat:')
    if at < 0:
        raise SystemExit('Clawd sprite table not found; the app has changed, keeping the current sprites')
    start = at
    while True:
        start = src.rfind('={', 0, start)
        if start < 0:
            raise SystemExit('could not find the start of the sprite table')
        # every entry before Laptop is closed, so only the table's own brace is left open
        if src.count('{', start + 1, at) == src.count('}', start + 1, at) + 1:
            break
    depth = 0
    for end in range(start + 1, len(src)):
        depth += {'{': 1, '}': -1}.get(src[end], 0)
        if depth == 0:
            break
    body = src[start + 1:end + 1]
    body = re.sub(r'"([^"]*)"\.split\("([^"]*)"\)', lambda m: json.dumps(m.group(1).split(m.group(2))), body)
    body = re.sub(r'([{,])([A-Za-z_][A-Za-z0-9_]*):', r'\1"\2":', body)
    return json.loads(body.replace(':!0', ':true').replace(':!1', ':false'))


def clawd_strips(asar):
    table = sprite_table(asar_file(asar, 'clawdQuestEngine'))
    strips = {}
    for anim, name in CLAWD_ANIMS.items():
        spec = table[name]
        w, h = spec['w'], spec['h']
        ox, oy = BODY_X - spec['a0'][0], BODY_Y - spec['a0'][1]
        cells = [None if c == '.' else int(c, 36) for c in spec['base']]
        frames = []
        for delta in [None] + spec['deltas']:
            for token in (delta.split(',') if delta else []):
                cells[int(token[:-1], 36)] = None if token[-1] == '.' else int(token[-1], 36)
            frame = {}
            for i, c in enumerate(cells):
                x, y = i % w + ox, i // w + oy
                if c is not None and 0 <= x < FRAME_W and 0 <= y < FRAME_H:
                    frame[(x, y)] = c
            frames.append(frame)
        strips[anim] = ([c.lower() for c in spec['palette']], frames)
    return strips


if __name__ == '__main__':
    command = sys.argv[1] if len(sys.argv) > 1 else 'default'
    if command == 'default':
        write(default_strips(), 'The Backstage pixel robot, drawn for this project (MIT), 12 frames a second.')
    elif command == 'clawd':
        asar = sys.argv[2] if len(sys.argv) > 2 else DEFAULT_ASAR
        write(clawd_strips(asar), 'Clawd, read from your own Claude desktop app. Anthropic\'s artwork: keep this file local, do not publish it.')
    else:
        raise SystemExit(__doc__)
